import * as Print from 'expo-print';

import * as Sharing from 'expo-sharing';

export const generateMentalHealthPDF =
  async (
    user: any,

    result: any,

    questions: any[],

    responses: any
  ) => {
    try {
      // PARSE RESPONSES
      const parsedResponses =
        responses
          ? JSON.parse(responses)
          : [];

      // CREATE HTML FOR RESPONSES
      const responseList =
        parsedResponses
          .map(
            (
              item: string,
              index: number
            ) => `
        <div style="
          margin-bottom:20px;
          padding:15px;
          border:1px solid #e2e8f0;
          border-radius:10px;
          background:#f8fafc;
        ">
          <h3 style="
            color:#1e293b;
          ">
            Question ${
              index + 1
            }
          </h3>

          <p style="
            color:#475569;
            line-height:24px;
          ">
            ${item}
          </p>
        </div>
      `
          )
          .join('');

      // HTML TEMPLATE
      const html = `
      <html>
      <body style="
        font-family: Arial;
        padding: 30px;
        background:#ffffff;
      ">
      
      <!-- HEADER -->
      <div style="
        text-align:center;
        margin-bottom:30px;
      ">
        <h1 style="
          color:#10b981;
          font-size:34px;
        ">
          PsyCare AI Mental Health Report
        </h1>

        <p style="
          color:#64748b;
          font-size:16px;
        ">
          AI Powered Mental Wellness Analysis
        </p>
      </div>

      <hr />

      <!-- USER INFO -->
      <h2 style="
        color:#1e293b;
      ">
        User Information
      </h2>

      <p>
        <strong>Email:</strong>
        ${user?.email || 'N/A'}
      </p>

      <p>
        <strong>Date:</strong>
        ${new Date().toLocaleDateString()}
      </p>

      <hr />

      <!-- AI RESULT -->
      <h2 style="
        color:#1e293b;
      ">
        AI Analysis Result
      </h2>

      <div style="
        background:#f8fafc;
        padding:20px;
        border-radius:12px;
        margin-top:20px;
      ">
        <p>
          <strong>Stress Score:</strong>
          ${result.stress_score}%
        </p>

        <p>
          <strong>Anxiety Score:</strong>
          ${result.anxiety_score}%
        </p>

        <p>
          <strong>Depression Score:</strong>
          ${result.depression_score}%
        </p>

        <p>
          <strong>Severity:</strong>
          ${result.overall_severity}
        </p>
      </div>

      <hr />

      <!-- RECOMMENDATION -->
      <h2 style="
        color:#1e293b;
      ">
        Recommendations
      </h2>

      <div style="
        background:#ecfeff;
        padding:20px;
        border-radius:12px;
      ">
        <p style="
          line-height:28px;
          color:#164e63;
        ">
          ${result.recommendations}
        </p>
      </div>

      <hr />

      <!-- USER RESPONSES -->
      <h2 style="
        color:#1e293b;
      ">
        User Responses
      </h2>

      ${responseList}

      <!-- FOOTER -->
      <div style="
        margin-top:40px;
        text-align:center;
      ">
        <p style="
          color:#94a3b8;
        ">
          Generated by PsyCare AI
        </p>
      </div>

      </body>
      </html>
      `;

      // GENERATE PDF
      const { uri } =
        await Print.printToFileAsync({
          html,
        });

      // SHARE / DOWNLOAD
      await Sharing.shareAsync(
        uri
      );

      return {
        success: true,
      };
    } catch (error) {
      console.log(
        'PDF Error:',
        error
      );

      return {
        success: false,
      };
    }
  };